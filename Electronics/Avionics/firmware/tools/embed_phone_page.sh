#!/bin/sh
# Regenerates src/phone_page_html.h from ../flight_computer_phone_v1.html so
# the board serves the same page at http://192.168.4.1/. Run from firmware/:
#   sh tools/embed_phone_page.sh
set -e
SRC=../flight_computer_phone_v1.html
OUT=src/phone_page_html.h
{
  echo '// GENERATED by tools/embed_phone_page.sh from flight_computer_phone_v1.html -- edit that file, then rerun.'
  echo '#pragma once'
  printf 'static const char PHONE_PAGE_HTML[] = R"HTML('
  cat "$SRC"
  echo ')HTML";'
} > "$OUT"
echo "wrote $OUT"
